"""The review hub: one static page that reviews the cards of every walkthrough (spaced repetition).

Layout (personal data, kept outside project repos):
    ~/learning/decks/<project>.json   written by render.py, one per walkthrough
    ~/learning/hub/index.html         this page (open it in a browser)
    ~/learning/hub/decks.js           all decks bundled as a script, so file:// works without a server
Progress is stored in the browser (localStorage) and can be exported / imported as JSON.
"""
import json
import os
from collections import Counter

from .strings import strings

ENGINE = os.path.dirname(os.path.abspath(__file__))


def build(learning: str) -> str:
    decks_dir = os.path.join(learning, "decks")
    hub_dir = os.path.join(learning, "hub")
    os.makedirs(hub_dir, exist_ok=True)
    decks = []
    for name in sorted(os.listdir(decks_dir)) if os.path.isdir(decks_dir) else []:
        if not name.endswith(".json"):
            continue
        with open(os.path.join(decks_dir, name), encoding="utf-8") as f:
            d = json.load(f)
        d["href"] = os.path.relpath(d["walkthrough"], hub_dir) if os.path.exists(d["walkthrough"]) else ""
        decks.append(d)
    lang = Counter(d.get("lang", "zh-TW") for d in decks).most_common(1)[0][0] if decks else "zh-TW"
    with open(os.path.join(hub_dir, "decks.js"), "w", encoding="utf-8") as f:
        f.write("// generated by the walkthrough skill (wt/hub.py); do not edit\nwindow.WT_DECKS = ")
        json.dump(decks, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    with open(os.path.join(ENGINE, "templates", "hub.html"), encoding="utf-8") as f:
        page = f.read()
    S = strings(lang)
    page = (page.replace("__LANG__", lang).replace("__TITLE__", S["hub_title"])
                .replace("__S__", json.dumps(S, ensure_ascii=False).replace("</", "<\\/")))
    out = os.path.join(hub_dir, "index.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(page)
    print(f"hub: {out} ({len(decks)} decks, {sum(len(d['cards']) for d in decks)} cards)")
    return out
